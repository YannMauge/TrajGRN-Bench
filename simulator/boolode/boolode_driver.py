from BoolODE import simulator as bo_sim  # noqa: E402
from BoolODE import utils as bo_utils  # noqa: E402
from BoolODE.model_generator import GenerateModel  # noqa: E402

DEFAULT_SIM_TIME = 8.0      # BEELINE used 5-15 (8 for bifurcating models)
DEFAULT_STEP = 0.01         # BoolODE default integration_step_size
DEFAULT_MODELTYPE = "hill"  # BEELINE setting
MAX_RETRIES = 10
EXTRA_OPTIONS = ("sim_time", "step", "modeltype")


def _bool_name(gene_index: int) -> str:
    """BoolODE node name of benchmark gene ``Gene{i}`` (rules use g1..gN)."""
    return f"g{gene_index + 1}"


def _settings(model_dir: Path, out_dir: Path, definition: str, ics: str,
              sim_time: float, step: float, modeltype: str) -> Dict:
    """Job settings as built by ``BoolODE.__process_jobs`` (defaults kept)."""
    empty = Path(model_dir, "")
    return {
        "name": "benchmark", "outprefix": out_dir,
        "modelpath": model_dir / definition, "icsPath": model_dir / ics,
        "simulation_time": sim_time, "integration_step_size": step,
        "num_cells": 1, "sample_cells": False, "nClusters": 1, "doParallel": False,
        "identical_pars": False, "sample_pars": False, "sample_std": 0.1,
        "parameter_inputs_path": empty, "parameter_set": empty,
        "interaction_strengths": empty, "species_type": empty,
        "burnin": False, "writeProtein": False, "normalizeTrajectory": False,
        "add_dummy": False, "max_parents": 1, "modeltype": modeltype,
    }


class BoolODEModel:
    """ODE model generated by BoolODE plus the initial-state vector logic of
    ``run_experiment.Experiment``."""

    def __init__(self, work_dir: Path, n_genes: int, sim_time: float, step: float, modeltype: str):
        model_dir, out_dir = work_dir / "model", work_dir / "out"
        out_dir.mkdir(parents=True, exist_ok=True)
        definition, ics = write_boolode_model_files(model_dir, n_genes)
        settings = _settings(model_dir, out_dir, definition, ics, sim_time, step, modeltype)
        self.mg = GenerateModel(settings, pd.DataFrame(), pd.DataFrame(), pd.DataFrame())
        self.model = SourceFileLoader("boolode_model", self.mg.path_to_ode_model.as_posix()).load_module()
        self.tspan = np.linspace(0, sim_time, int(sim_time / step))
        self.par_names = sorted(self.mg.ModelSpec["pars"].keys())
        vm = self.mg.varmapper
        self.rev = {v: k for k, v in vm.items()}
        self.rna_index = [i for i in range(len(vm)) if "x_" in vm[i]]
        self.protein_index = [i for i in range(len(vm)) if "p_" in vm[i]]
        self.gene_rows = {g: self.rev["x_" + g] for g in self.mg.genelist}
        self.x_max = self.mg.kineticParameterDefaults["x_max"]
        self.ss = self._initial_state(bo_utils.checkValidInputPath(settings["icsPath"]))

    def _initial_state(self, ics_df: pd.DataFrame) -> np.ndarray:
        """Same initial-state rules as ``Experiment`` (ics file; 0.01 otherwise)."""
        import ast
        ss = np.zeros(len(self.mg.varmapper))
        icsmap = {}
        if not ics_df.empty:
            spec = ics_df.loc[0]
            icsmap = dict(zip(ast.literal_eval(spec["Genes"]), ast.literal_eval(spec["Values"])))
        for g in self.mg.genelist:
            ss[self.rev["x_" + g]] = icsmap.get(g, 0.01) if icsmap else 1.0
        for p in self.mg.proteinlist:
            ss[self.rev["p_" + p]] = icsmap.get(p, 0.01) if icsmap else 20.0
        return ss

    def simulate(self, seed: int, ko_gene: Optional[str] = None) -> np.ndarray:
        """One stochastic trajectory; returns mRNA values (genes × len(tspan))."""
        pars_dict = dict(self.mg.ModelSpec["pars"])
        ss = self.ss.copy()
        if ko_gene is not None:
            pars_dict["m_" + ko_gene] = 0.0
            ss[self.rev["x_" + ko_gene]] = 0.0
        pars = [pars_dict[k] for k in self.par_names]
        y0 = bo_sim.getInitialCondition(
            ss, self.mg.ModelSpec, self.rna_index, self.protein_index,
            self.mg.genelist, self.mg.proteinlist, self.mg.varmapper, self.rev,
        )
        traj = bo_sim.simulateModel(self.model.Model, y0, pars, True, self.tspan, seed)
        # eulersde allocates len(tspan)+1 rows; the extra trailing row is never
        # filled (upstream only reads rows 1..len(tspan)-1), so drop it.
        traj = np.asarray(traj)[: len(self.tspan)]
        return traj.T[[self.gene_rows[g] for g in self.mg.genelist], :]


def _sample_wt_trajectory(model: BoolODEModel, base_seed: int) -> Tuple[np.ndarray, int]:
    """Upstream ``simulateAndSample`` retry heuristic (seed += 1000 per try,
    re-simulate while some timestep has every gene below 10% of x_max),
    capped at MAX_RETRIES. Returns the trajectory and the accepted seed."""
    seed = base_seed
    for _ in range(MAX_RETRIES + 1):
        seed += 1000
        x = model.simulate(seed)
        if not np.any(x[:, 1:].max(axis=0) < 0.1 * model.x_max):
            return x, seed
    print(f"[BoolODE] trajectory seed {base_seed}: still collapsed after {MAX_RETRIES} retries; kept.")
    return x, seed


def simulate_runs(cfg: SimulatorCommonConfig, ko_labels: Sequence[str], write_ko_files: bool) -> None:
    """Simulate ``cfg.n_runs`` replicates (WT and, if requested, each KO).

    Writes ``data_<r>.txt`` (WT only) or ``data_<r>_ko_<label>.txt`` (WT as
    ``ko_WT`` + each KO), plus shared files and the signed true GRN.
    """
    sim_time = float(cfg.extra.get("sim_time", DEFAULT_SIM_TIME))
    step = float(cfg.extra.get("step", DEFAULT_STEP))
    modeltype = cfg.extra.get("modeltype", DEFAULT_MODELTYPE)
    model = BoolODEModel(cfg.output_folder / "boolode_model", cfg.n_genes, sim_time, step, modeltype)

    n_grid = len(model.tspan)
    grid_idx = np.round(np.linspace(0, n_grid - 1, cfg.n_time_bins)).astype(int)
    labels = cfg.time_labels()
    print(f"[BoolODE] {modeltype} model, T={sim_time}, step={step}: {cfg.n_cells} trajectories, "
          f"bins at t={np.round(model.tspan[grid_idx], 3).tolist()} -> labels {labels.tolist()}")

    # BoolODE's own degradation rates (mRNA l_x_g, protein l_p_g, per BoolODE
    # time unit) in timepoint-label units: consecutive labels (Δ apart) are
    # T/(n_time_bins-1) BoolODE time units apart.
    label_step = float(labels[1] - labels[0]) if len(labels) > 1 else 1.0
    boolode_per_label = (sim_time / (cfg.n_time_bins - 1)) / label_step
    pars = model.mg.ModelSpec["pars"]
    gene_rates = np.array([[pars["l_x_" + _bool_name(i)], pars["l_p_" + _bool_name(i)]]
                           for i in range(cfg.n_genes)], dtype=float) * boolode_per_label
    rates = np.vstack([gene_rates.mean(axis=0, keepdims=True), gene_rates])  # stimulus row first
    write_shared_files(cfg.output_folder, cfg.gene_names, rates)
    true_dir = cfg.output_folder.parent / "True"
    true_dir.mkdir(parents=True, exist_ok=True)
    gene_of_label = {name: _bool_name(i) for i, name in enumerate(cfg.gene_names)}

    for run_index in range(1, cfg.n_runs + 1):
        run_seed = cfg.run_seed(run_index)
        rng = np.random.default_rng(run_seed)
        # Balanced, seeded assignment of trajectories to time bins.
        bins = rng.permutation(np.resize(np.arange(cfg.n_time_bins), cfg.n_cells))
        times = labels[bins]
        order = np.argsort(times, kind="stable")
        print(f"Run {run_index} (seed {run_seed})...")
        np.save(true_dir / f"inter_{run_index}", get_benchmark_grn(cfg.n_genes).build_true_interaction_matrix())

        conditions: List[Tuple[str, Optional[str]]] = [("WT", None)]
        conditions += [(label, gene_of_label[label]) for label in ko_labels]
        scale: Optional[float] = None
        accepted_seeds: List[int] = []
        for cond_index, (label, ko_gene) in enumerate(conditions):
            expr = np.zeros((cfg.n_cells, cfg.n_genes))
            for cell in range(cfg.n_cells):
                if ko_gene is None:
                    traj, seed = _sample_wt_trajectory(model, run_seed * 100_000 + cell)
                    accepted_seeds.append(seed)
                else:
                    traj = model.simulate(accepted_seeds[cell], ko_gene)
                values = traj[:, grid_idx[bins[cell]]]
                expr[cell] = [values[model.mg.genelist.index(_bool_name(i))] for i in range(cfg.n_genes)]
            expr = np.clip(expr, 0.0, None)
            if scale is None:  # WT max -> 100; KOs reuse the WT scale
                mx = float(expr.max())
                scale = 100.0 / mx if mx > 0 else 1.0
            counts = np.random.default_rng([run_seed, cond_index]).poisson(expr * scale)
            name = f"data_{run_index}.txt" if not write_ko_files else f"data_{run_index}_ko_{label}.txt"
            _write_data_file(cfg.output_folder / name, times[order], counts[order], cfg.stimulus_value)


def _write_data_file(path: Path, times: np.ndarray, counts: np.ndarray, stimulus_value: int) -> None:
    n_cells, n_genes = counts.shape
    data = np.zeros((n_cells + 1, n_genes + 2), dtype=int)
    data[0, 1:] = np.arange(n_genes + 1)
    data[1:, 0] = times
    data[1:, 1] = int(stimulus_value) * (times > 0)
    data[1:, 2:] = counts
    np.savetxt(path, data.T, fmt="%d", delimiter="\t")
