"""BoolODE driver shared by the WT and KO entry scripts.

The vendored BoolODE package (``BoolODE/``) is left untouched: we use its
model generator (Boolean rules -> ODE model) and its SDE integrator
(``simulator.simulateModel``), and only orchestrate the runs here.

How cells and timepoints are produced (as in BoolODE, one cell = one point of
one independently simulated trajectory):
  * ``n_cells`` trajectories are simulated on ``tspan = linspace(0, T, T/step)``
    (BoolODE defaults: step 0.01, hill model as used in BEELINE);
  * ``n_time_bins`` evenly spaced grid points are selected and each trajectory
    is assigned to exactly one of them (balanced, seeded), giving one cell;
  * timepoint labels are shared with the other simulators (0, 10, …, 90).

Knockouts are re-simulated (BoolODE has no native KO): the KO gene's
production rate ``m_<gene>`` is set to 0 and its initial mRNA/protein to 0, so
it stays exactly at 0 (the noise term is proportional to sqrt(x)); its rule and
outgoing regulation are unchanged, so its targets respond. WT and each KO use
the same per-trajectory seeds and bin assignment (common random numbers).

Seeding: every trajectory uses ``run_seed * 100_000 + cell_id`` (BoolODE's
integrator re-seeds numpy's global RNG with it), so replicates differ and runs
are reproducible. BoolODE's upstream retry heuristic (re-simulate when every
gene drops below 10% of x_max) is applied to WT, capped at ``MAX_RETRIES``.
Each KO trajectory reuses the seed accepted for the same WT cell (same noise,
same selection), and is never retried itself: a collapsed network is a
legitimate KO outcome.
"""

from __future__ import annotations

import sys
from importlib.machinery import SourceFileLoader
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
